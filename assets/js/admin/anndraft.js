/* ═══════════════════════════════════════════════════════════
   anndraft.js  —  AI Announcement Drafting
   Reads current system data, drafts announcement for admin
   to review and edit before sending manually.

   HOW TO USE:
   1. Add to Admin.html BEFORE </body>:
      <link rel="stylesheet" href="../assets/css/anndraft.css">
      <script src="../assets/js/anndraft.js"></script>
      (must come AFTER admin.js)

   2. The script auto-patches both announcement composers
      (Settings tab + modal) on DOMContentLoaded.
═══════════════════════════════════════════════════════════ */

/* No API key lives in this file anymore. Drafts are generated by the server
   (assets/php/draft_announcement.php), which keeps the key private. */
const ANN_DRAFT_ENDPOINT = '../assets/php/draft_announcement.php';

/* ── Draft context options ───────────────────────────────── */
const draftContexts = [
    { value: 'semester_reminder', label: '📅 Semester reminder' },
    { value: 'low_performance', label: '📉 Low class performance alert' },
    { value: 'quiz_deadline', label: '⏰ Upcoming quiz deadlines' },
    { value: 'xp_milestone', label: '⭐ XP milestone / leaderboard update' },
    { value: 'system_maintenance', label: '🔧 System maintenance notice' },
    { value: 'flagged_quiz', label: '⚠️ Flagged quiz resolution' },
    { value: 'grade_boost_remind', label: '🎓 Grade boost redemption reminder' },
];

/* ── Inject AI draft UI into both composers ──────────────── */
document.addEventListener('DOMContentLoaded', () => {
    // Patch Settings tab composer
    patchComposer('ann-title', 'ann-body', 'ann-target', 'ann-priority', 'settings');
    // Patch modal composer
    patchComposer('ann-title-m', 'ann-body-m', 'ann-target-m', 'ann-priority-m', 'modal');
});

function patchComposer(titleId, bodyId, targetId, priorityId, composerId) {
    const titleEl = document.getElementById(titleId);
    if (!titleEl) return;

    // Find the parent ann-form
    const form = titleEl.closest('.ann-form');
    if (!form) return;

    // Inject AI draft panel before the first form-group
    const draftPanel = document.createElement('div');
    draftPanel.className = 'ann-draft-panel';
    draftPanel.id = `draft-panel-${composerId}`;
    draftPanel.innerHTML = `
    <div class="ann-draft-header">
      <span class="ann-draft-icon">🤖</span>
      <span class="ann-draft-label">AI Draft Assistant</span>
      <span class="ann-draft-sub">Generate a draft based on current system data</span>
    </div>
    <div class="ann-draft-context-row">
      <select class="ann-context-select" id="ann-context-${composerId}">
        <option value="">Select announcement type...</option>
        ${draftContexts.map(c => `<option value="${c.value}">${c.label}</option>`).join('')}
      </select>
      <button class="ann-draft-btn" id="ann-draft-btn-${composerId}"
        onclick="generateDraft('${titleId}','${bodyId}','${targetId}','${priorityId}','${composerId}')">
        ✨ Generate Draft
      </button>
    </div>
    <div class="ann-draft-context-row" style="margin-top:.5rem">
      <input type="text" class="ann-context-select" id="ann-instruction-${composerId}" maxlength="600"
        placeholder="Optional: topic or instruction (e.g. remind students about Friday's midterm)" style="flex:1;min-width:0">
      <select class="ann-context-select" id="ann-tone-${composerId}" style="max-width:150px">
        <option value="friendly">Friendly</option>
        <option value="formal">Formal</option>
        <option value="urgent">Urgent</option>
        <option value="encouraging">Encouraging</option>
      </select>
    </div>
    <div class="ann-draft-status" id="ann-draft-status-${composerId}" style="display:none"></div>
    <div class="ann-draft-preview" id="ann-draft-preview-${composerId}" style="display:none">
      <div class="ann-preview-label">📋 AI Draft Preview — click the text to edit. Nothing is sent until you press Send Announcement.</div>
      <div class="ann-preview-title" id="ann-preview-title-${composerId}" contenteditable="true" spellcheck="true"></div>
      <div class="ann-preview-body" id="ann-preview-body-${composerId}" contenteditable="true" spellcheck="true"></div>
      <div class="ann-preview-actions">
        <button class="ann-use-btn" onclick="useDraft('${titleId}','${bodyId}','${composerId}')">✅ Use This Draft</button>
        <button class="ann-regen-btn" onclick="generateDraft('${titleId}','${bodyId}','${targetId}','${priorityId}','${composerId}')">↻ Regenerate</button>
        <button class="ann-regen-btn" onclick="copyDraft('${composerId}')">📋 Copy</button>
        <button class="ann-discard-btn" onclick="discardDraft('${composerId}')">✕ Discard</button>
      </div>
    </div>
  `;

  form.appendChild(draftPanel);
}

/* ── Generate AI draft (server-side) ─────────────────────── */
async function generateDraft(titleId, bodyId, targetId, priorityId, composerId) {
  const contextEl = document.getElementById(`ann-context-${composerId}`);
  const instructionEl = document.getElementById(`ann-instruction-${composerId}`);
  const toneEl = document.getElementById(`ann-tone-${composerId}`);
  const context = contextEl?.value || '';
  const instruction = (instructionEl?.value || '').trim();

  if (!context && !instruction) {
    showToast('⚠️', 'Select an announcement type or type a topic first.');
    return;
  }

  const btn = document.getElementById(`ann-draft-btn-${composerId}`);
  const statusEl = document.getElementById(`ann-draft-status-${composerId}`);
  const previewEl = document.getElementById(`ann-draft-preview-${composerId}`);

  btn.disabled = true;
  btn.textContent = '⏳ Drafting...';
  statusEl.style.display = 'flex';
  statusEl.innerHTML = `
    <span class="ci-dot"></span><span class="ci-dot"></span><span class="ci-dot"></span>
    <span class="ci-loading-text">Drafting your announcement...</span>`;
  previewEl.style.display = 'none';

  try {
    const res = await fetch(ANN_DRAFT_ENDPOINT, {
      method: 'POST',
      credentials: 'same-origin',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        context,
        instruction,
        tone: toneEl?.value || 'friendly',
        target: document.getElementById(targetId)?.value || 'All Users',
        priority: document.getElementById(priorityId)?.value || 'Normal'
      })
    });

    let data = null;
    try { data = await res.json(); } catch (parseError) { data = null; }

    if (!res.ok || !data || !data.success || !data.draft) {
      throw new Error((data && data.message) || `The server returned an error (${res.status}).`);
    }

    statusEl.style.display = 'none';
    previewEl.style.display = 'block';
    document.getElementById(`ann-preview-title-${composerId}`).textContent = data.draft.title;
    document.getElementById(`ann-preview-body-${composerId}`).textContent = data.draft.body;

  } catch (err) {
    console.error('Draft error:', err);
    statusEl.style.display = 'flex';
    statusEl.textContent = '';
    const msg = document.createElement('span');
    msg.style.cssText = 'color:#f87171;font-size:.78rem';
    msg.textContent = '⚠️ ' + (err.message || 'Could not generate a draft. Try again.');
    statusEl.appendChild(msg);
  } finally {
    btn.disabled = false;
    btn.textContent = '✨ Generate Draft';
  }
}

/* ── Read the (possibly edited) draft ────────────────────── */
function readDraft(composerId) {
  return {
    title: (document.getElementById(`ann-preview-title-${composerId}`)?.textContent || '').trim(),
    body: (document.getElementById(`ann-preview-body-${composerId}`)?.textContent || '').trim()
  };
}

/* ── Apply draft to form fields (does NOT send) ──────────── */
function useDraft(titleId, bodyId, composerId) {
  const previewEl = document.getElementById(`ann-draft-preview-${composerId}`);
  const { title, body } = readDraft(composerId);

  if (title) document.getElementById(titleId).value = title;
  if (body)  document.getElementById(bodyId).value  = body;

  previewEl.style.display = 'none';
  showToast('✅', 'Draft applied — review and edit before sending!');

  document.getElementById(titleId)?.scrollIntoView({ behavior: 'smooth', block: 'center' });
  document.getElementById(titleId)?.focus();
}

/* ── Copy draft to clipboard ─────────────────────────────── */
async function copyDraft(composerId) {
  const { title, body } = readDraft(composerId);
  const text = `${title}\n\n${body}`.trim();
  try {
    await navigator.clipboard.writeText(text);
    showToast('📋', 'Draft copied to clipboard.');
  } catch (error) {
    console.error('Copy failed:', error);
    showToast('⚠️', 'Could not copy automatically. Select the text and copy it manually.');
  }
}

/* ── Discard draft ───────────────────────────────────────── */
function discardDraft(composerId) {
  document.getElementById(`ann-draft-preview-${composerId}`).style.display = 'none';
  document.getElementById(`ann-draft-status-${composerId}`).style.display  = 'none';
  document.getElementById(`ann-context-${composerId}`).value = '';
}